const THRESHOLDS_17 = [0, 15, 30, 45, 60, 75, 90, 105, 120, 135, 150, 165, 180, 195, 210, 225, 240];

const CONFIGS: Record<"2x2" | "4x4" | "8x8", PatterningConfig> = {
  "2x2": { blockSize: 2, patterns: PATTERNS_2X2, thresholds: [0, 51, 102, 153, 204] },
  "4x4": { blockSize: 4, patterns: PATTERNS_4X4, thresholds: THRESHOLDS_17 },
  "8x8": { blockSize: 8, patterns: PATTERNS_8X8, thresholds: THRESHOLDS_17 },
};

export function applyPatterningInPlace(
  image: ImageBuffer,
  palette: Palette,
  variant: "2x2" | "4x4" | "8x8"
): void {
  const { blockSize, patterns, thresholds } = CONFIGS[variant];
  const { width, height, data } = image;

  for (let by = 0; by < height; by += blockSize) {
    for (let bx = 0; bx < width; bx += blockSize) {
      // ブロック内の平均色を計算
      let sumR = 0;
      let sumG = 0;
      let sumB = 0;
      let count = 0;
      for (let py = 0; py < blockSize && by + py < height; py++) {
        for (let px = 0; px < blockSize && bx + px < width; px++) {
          const i = ((by + py) * width + bx + px) * 4;
          sumR += data[i];
          sumG += data[i + 1];
          sumB += data[i + 2];
          count++;
        }
      }
      const avgR = Math.floor(sumR / count);
      const avgG = Math.floor(sumG / count);
      const avgB = Math.floor(sumB / count);

      // 明度からパターン段階を選択
      const brightness = luma(avgR, avgG, avgB);
      let patternIndex = 0;
      for (let i = thresholds.length - 1; i >= 0; i--) {
        if (brightness >= thresholds[i]) {
          patternIndex = i;
          break;
        }
      }

      // 明色（平均色）と暗色（平均色-50）の最近傍パレット色
      const light = palette[findClosestIndex({ r: avgR, g: avgG, b: avgB }, palette)];
      const dark = palette[
        findClosestIndex(
          { r: Math.max(0, avgR - 50), g: Math.max(0, avgG - 50), b: Math.max(0, avgB - 50) },
          palette
        )
      ];

      const pattern = patterns[patternIndex];
      for (let py = 0; py < blockSize && by + py < height; py++) {
        for (let px = 0; px < blockSize && bx + px < width; px++) {
          const c = pattern[py][px] ? light : dark;
          const i = ((by + py) * width + bx + px) * 4;
          data[i] = c.r;
          data[i + 1] = c.g;
          data[i + 2] = c.b;
        }
      }
    }
  }
}
